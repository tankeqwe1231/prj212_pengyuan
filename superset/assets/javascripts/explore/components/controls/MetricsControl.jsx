import React, { useRef, useState } from 'react';
import PropTypes from 'prop-types';
import ControlHeader from '../ControlHeader';
import { t } from '../../../locales';
import OnPasteSelect from '../../../components/OnPasteSelect';
import WindowedMenuList from '../../../components/WindowedMenuList';
import { normalizeSelectValue } from '../../../components/selectUtils';
import MetricDefinitionOption from '../MetricDefinitionOption';
import MetricDefinitionValue from '../MetricDefinitionValue';
import AdhocMetric from '../../AdhocMetric';
import columnType from '../../propTypes/columnType';
import savedMetricType from '../../propTypes/savedMetricType';
import adhocMetricType from '../../propTypes/adhocMetricType';
import { AGGREGATES } from '../../constants';

const propTypes = {
  name: PropTypes.string.isRequired,
  onChange: PropTypes.func,
  value: PropTypes.oneOfType([
    PropTypes.arrayOf(PropTypes.oneOfType([PropTypes.string, adhocMetricType])),
    PropTypes.oneOfType([PropTypes.string, adhocMetricType]),
  ]),
  columns: PropTypes.arrayOf(columnType),
  savedMetrics: PropTypes.arrayOf(savedMetricType),
  multi: PropTypes.bool,
  datasourceType: PropTypes.string,
};

const defaultProps = {
  onChange: () => {},
};

function isDictionaryForAdhocMetric(value) {
  return value && !(value instanceof AdhocMetric) && value.column && value.aggregate && value.label;
}

// adhoc metrics are stored as dictionaries in URL params. We convert them back into the
// AdhocMetric class for typechecking, consistency and instance method access.
function coerceAdhocMetrics(value) {
  if (!value) {
    return [];
  }
  if (!Array.isArray(value)) {
    if (isDictionaryForAdhocMetric(value)) {
      return [new AdhocMetric(value)];
    }
    return [value];
  }
  return value.map((val) => {
    if (isDictionaryForAdhocMetric(val)) {
      return new AdhocMetric(val);
    }
    return val;
  });
}

function getDefaultAggregateForColumn(column) {
  const type = column.type;
  if (typeof type !== 'string') {
    return AGGREGATES.COUNT;
  } else if (type === '' || type === 'expression') {
    return AGGREGATES.SUM;
  } else if (type.match(/.*char.*/i) || type.match(/string.*/i) || type.match(/.*text.*/i)) {
    return AGGREGATES.COUNT_DISTINCT;
  } else if (type.match(/.*int.*/i) || type === 'LONG' || type === 'DOUBLE' || type === 'FLOAT') {
    return AGGREGATES.SUM;
  } else if (type.match(/.*bool.*/i)) {
    return AGGREGATES.MAX;
  } else if (type.match(/.*time.*/i)) {
    return AGGREGATES.COUNT;
  } else if (type.match(/unknown/i)) {
    return AGGREGATES.COUNT;
  }
  return null;
}

const sqlaAutoGeneratedMetricRegex = /^(LONG|DOUBLE|FLOAT)?(SUM|AVG|MAX|MIN|COUNT)\([A-Z_][A-Z0-9_]*\)$/i;
const druidAutoGeneratedMetricRegex = /^(LONG|DOUBLE|FLOAT)?(SUM|MAX|MIN|COUNT)\([A-Z_][A-Z0-9_]*\)$/i;

function MetricsControl(incomingProps) {
  const props = { ...incomingProps };
  Object.keys(MetricsControl.defaultProps || {}).forEach(key => {
    if (typeof props[key] === 'undefined') props[key] = MetricsControl.defaultProps[key];
  });
  const propsRef = useRef(props);
  const [state, setState] = useState(() => ({
    aggregateInInput: null,
    inputValue: '',
    options: optionsForSelect(propsRef.current),
    value: coerceAdhocMetrics(propsRef.current.value)
  }));
  const stateRef = useRef(state);
  stateRef.current = state;
  const updateState = (update, callback) => {
    const previous = stateRef.current;
    const partial = typeof update === 'function' ? update(previous, propsRef.current) : update;
    if (partial == null) return;
    const next = {
      ...previous,
      ...partial
    };
    stateRef.current = next;
    setState(next);
    if (typeof callback === 'function') callback();
  };
  const optionRendererRef = useRef(option => <MetricDefinitionOption option={option} />);
  const valueRendererRef = useRef(option => <MetricDefinitionValue option={option} onMetricEdit={onMetricEdit} columns={propsRef.current.columns} multi={propsRef.current.multi} datasourceType={propsRef.current.datasourceType} />);
  const inputRefRef = useRef(null);
  const clearedAggregateInInputRef = useRef(undefined);
  function onMetricEdit(changedMetric) {
    let newValue = stateRef.current.value.map(value => {
      if (value.optionName === changedMetric.optionName) {
        return changedMetric;
      }
      return value;
    });
    if (!propsRef.current.multi) {
      newValue = newValue[0];
    }
    propsRef.current.onChange(newValue);
  }
  function onChange(opts) {
    let transformedOpts = opts;
    let aggregateSelected = false;
    if (!propsRef.current.multi) {
      transformedOpts = [opts].filter(option => option);
    }
    let optionValues = transformedOpts.map(option => {
      if (option.metric_name) {
        return option.metric_name;
      } else if (option.column_name) {
        const clearedAggregate = clearedAggregateInInputRef.current;
        clearedAggregateInInputRef.current = null;
        return new AdhocMetric({
          column: option,
          aggregate: clearedAggregate || getDefaultAggregateForColumn(option)
        });
      } else if (option instanceof AdhocMetric) {
        return option;
      } else if (option.aggregate_name) {
        aggregateSelected = true;
        const newValue = `${option.aggregate_name}()`;
        updateState({
          aggregateInInput: option.aggregate_name,
          inputValue: newValue
        });
        // we need to set a timeout here or the selectionWill be overwritten
        // by some browsers (e.g. Chrome)
        setTimeout(() => {
          if (inputRefRef.current) {
            inputRefRef.current.focus();
            inputRefRef.current.setSelectionRange(newValue.length - 1, newValue.length - 1);
          }
        }, 0);
        return null;
      }
      return null;
    }).filter(option => option);
    if (!propsRef.current.multi) {
      optionValues = optionValues[0];
    }
    if (!aggregateSelected) {
      updateState({
        inputValue: ''
      });
    }
    propsRef.current.onChange(optionValues);
  }
  function checkIfAggregateInInput(input, actionMeta) {
    if (actionMeta && actionMeta.action !== 'input-change') {
      return input;
    }
    let nextState = {
      aggregateInInput: null,
      inputValue: input
    };
    Object.keys(AGGREGATES).forEach(aggregate => {
      if (input.toLowerCase().startsWith(aggregate.toLowerCase() + '(')) {
        nextState = {
          aggregateInInput: aggregate,
          inputValue: input
        };
      }
    });
    clearedAggregateInInputRef.current = stateRef.current.aggregateInInput;
    updateState(nextState);
    return input;
  }
  function optionsForSelect(props) {
    const options = [...props.columns, ...Object.keys(AGGREGATES).map(aggregate => ({
      aggregate_name: aggregate
    })), ...props.savedMetrics];
    return options.map(option => {
      if (option.metric_name) {
        return {
          ...option,
          optionName: option.metric_name
        };
      } else if (option.column_name) {
        return {
          ...option,
          optionName: '_col_' + option.column_name
        };
      } else if (option.aggregate_name) {
        return {
          ...option,
          optionName: '_aggregate_' + option.aggregate_name
        };
      }
      notify.error(`provided invalid option to MetricsControl, ${option}`);
      return null;
    });
  }
  function isAutoGeneratedMetric(savedMetric) {
    if (propsRef.current.datasourceType === 'druid') {
      return druidAutoGeneratedMetricRegex.test(savedMetric.verbose_name);
    }
    return sqlaAutoGeneratedMetricRegex.test(savedMetric.expression);
  }
  function selectFilterOption(option, filterValue) {
    const optionData = option.data || option;
    if (stateRef.current.aggregateInInput) {
      let endIndex = filterValue.length;
      if (filterValue.endsWith(')')) {
        endIndex = filterValue.length - 1;
      }
      const valueAfterAggregate = filterValue.substring(filterValue.indexOf('(') + 1, endIndex);
      return optionData.column_name && optionData.column_name.toLowerCase().indexOf(valueAfterAggregate.toLowerCase()) >= 0;
    }
    return optionData.optionName && (!optionData.metric_name || !isAutoGeneratedMetric(optionData)) && optionData.optionName.toLowerCase().indexOf(filterValue.toLowerCase()) >= 0;
  }
  function receiveProps(nextProps) {
    if (propsRef.current.columns !== nextProps.columns || propsRef.current.savedMetrics !== nextProps.savedMetrics) {
      updateState({
        options: optionsForSelect(nextProps)
      });
      propsRef.current.onChange([]);
    }
    if (propsRef.current.value !== nextProps.value) {
      updateState({
        value: coerceAdhocMetrics(nextProps.value)
      });
    }
  }
  const previousIncomingPropsRef = useRef(incomingProps);
  const incomingKeys = Object.keys(incomingProps);
  const previousIncomingProps = previousIncomingPropsRef.current;
  const incomingPropsChanged = incomingKeys.length !== Object.keys(previousIncomingProps).length || incomingKeys.some(key => incomingProps[key] !== previousIncomingProps[key]);
  if (incomingPropsChanged) {
    receiveProps(props);
    previousIncomingPropsRef.current = incomingProps;
  }
  propsRef.current = props;
  // TODO figure out why the dropdown isnt appearing as soon as a metric is selected
  const selectedValue = normalizeSelectValue(propsRef.current.multi ? stateRef.current.value : stateRef.current.value[0], stateRef.current.options, 'optionName', 'label', propsRef.current.multi);
  return <div className="metrics-select">
        <ControlHeader {...propsRef.current} />
        <OnPasteSelect isMulti={propsRef.current.multi} name={`select-${propsRef.current.name}`} placeholder={t('choose a column or aggregate function')} options={stateRef.current.options} value={selectedValue} valueKey="optionName" isClearable closeMenuOnSelect onChange={onChange} formatOptionLabel={(option, meta) => meta.context === 'menu' ? optionRendererRef.current(option) : valueRendererRef.current(option)} getOptionLabel={option => option.label || option.metric_name || option.column_name || option.aggregate_name || option.optionName} inputValue={stateRef.current.inputValue} onInputChange={checkIfAggregateInInput} inputRef={input => {
      inputRefRef.current = input;
    }} filterOption={selectFilterOption} components={{
      MenuList: WindowedMenuList
    }} />
      </div>;
}


export default MetricsControl;

MetricsControl.propTypes = propTypes;
MetricsControl.defaultProps = defaultProps;
